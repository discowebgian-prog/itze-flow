// Encuentra el país a partir de lo que lee el escáner: código de 2 letras (CA),
// de 3 letras como figura en el pasaporte (CAN) o el nombre en español.
const normCountry = (t) =>
  String(t || '').normalize('NFD').replace(/[̀-ͯ]/g, '').trim().toUpperCase();
const COUNTRY_ALIASES = { D: 'DE', UK: 'GB', GBD: 'GB', GBN: 'GB', GBO: 'GB', GBS: 'GB', GBP: 'GB' };
export const findCountry = (value) => {
  const v = normCountry(value);
  if (!v) return null;
  const code = COUNTRY_ALIASES[v] || v;
  return (
    COUNTRIES.find((c) => c.code === code || c.iso3 === code) ||
    COUNTRIES.find((c) => normCountry(c.name) === v) ||
    null
  );
};
